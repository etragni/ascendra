"""Reporter: renders the plan for humans (Markdown, ready to paste in a PR) and machines (JSON)."""
from __future__ import annotations

from itertools import groupby
from pathlib import Path

from ascendra.agents.base import Agent
from ascendra.models import Severity, UpgradeContext

ICON = {"blocker": "⛔", "warning": "⚠️", "info": "ℹ️", "high": "🔴", "medium": "🟠", "low": "🟢"}


def render_markdown(ctx: UpgradeContext) -> str:
    L = [f"# Upgrade plan: {ctx.subject} ({ctx.target}) {ctx.current_version} → {ctx.target_version}", ""]
    if ctx.blockers:
        L += [f"**Status: {len(ctx.blockers)} blocker(s) must be resolved before upgrading.**", ""]
    else:
        L += ["**Status: no blockers found.**", ""]
    if ctx.executive_summary:
        L += ["## Summary", "", ctx.executive_summary, ""]

    L += ["## Findings", ""]
    if ctx.findings:
        L += ["| | Category | Component | Issue | Fix |", "|---|---|---|---|---|"]
        order = {Severity.BLOCKER: 0, Severity.WARNING: 1, Severity.INFO: 2}
        for f in sorted(ctx.findings, key=lambda f: order[f.severity]):
            L.append(f"| {ICON[f.severity.value]} | {f.category} | {f.component} | {f.message} | {f.fix or ''} |")
    else:
        L.append("None.")
    L.append("")

    L += ["## Plan", ""]
    for (wave, name), steps in groupby(ctx.plan, key=lambda s: (s.wave, s.wave_name)):
        L.append(f"### Wave {wave}: {name}")
        L.append("")
        for s in steps:
            ver = f" `{s.from_version}` → `{s.to_version}`" if s.to_version else ""
            L.append(f"- [ ] **{s.action}** {s.target}{ver}: {s.rationale}")
        L.append("")

    if ctx.risks:
        L += ["## Component risk", ""]
        for r in sorted(ctx.risks, key=lambda r: ["high", "medium", "low"].index(r.level.value)):
            L.append(f"### {ICON[r.level.value]} {r.component} ({r.level.value})")
            L += ["", r.summary, ""]
            for b in r.breaking_changes:
                L.append(f"- {b}")
            for a in r.recommended_actions:
                L.append(f"- [ ] {a}")
            L += ["", f"_assessed by {r.assessed_by}_", ""]

    L += ["## Agent trace", "", "| Agent | Status | Detail | Time |", "|---|---|---|---|"]
    for run in ctx.runs:
        L.append(f"| {run.agent} | {run.status} | {run.detail} | {run.seconds:.1f}s |")
    L += ["", "_Generated by [Ascendra](https://github.com/evantragni/ascendra). Review every step: Ascendra proposes, humans approve._"]
    return "\n".join(L)


class ReporterAgent(Agent):
    name = "reporter"
    role = "Writes the upgrade plan as Markdown and JSON"

    def __init__(self, out_dir: Path) -> None:
        self.out_dir = out_dir

    def run(self, ctx: UpgradeContext) -> str:
        self.out_dir.mkdir(parents=True, exist_ok=True)
        (self.out_dir / "upgrade-plan.json").write_text(ctx.model_dump_json(indent=2))
        (self.out_dir / "upgrade-plan.md").write_text(render_markdown(ctx))
        return f"wrote {self.out_dir}/upgrade-plan.md and .json"
